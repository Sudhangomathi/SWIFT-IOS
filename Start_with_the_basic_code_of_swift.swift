// Start with the basic code of swift:
 
print("Hello, World!")
print("Welcome to iOS Development")

/*
Output:

Hello, World!
Welcome to iOS Development
*/

// MARK: - Expressions & Numbers

print(100)
print(10 + 20)
print("10 + 20")

/*
Output:

100
30
10 + 20
*/

// MARK: - Variables (var)
// A var variable can change its value.

var age = 21
print(age)

/*
Output:

21
*/

age = 22
print(age)

/*
Output:

22
*/

// MARK: - Constants (let)
// A let constant cannot be reassigned after its initial value.

let country = "India"
print(country)

/*
Output:

India
*/
